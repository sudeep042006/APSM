import axios from "axios";
import Automation from "./automation.model.js";
import cloudinary from "../../config/cloudinary.js";
import streamifier from "streamifier";
import { createAndDispatchJob } from "./automation.queue.js";

const uploadToCloudinary = (fileBuffer) => {
  return new Promise((resolve, reject) => {
    const stream = cloudinary.uploader.upload_stream(
      { resource_type: "auto" },
      (error, result) => {
        if (error) return reject(error);
        resolve(result);
      },
    );
    streamifier.createReadStream(fileBuffer).pipe(stream);
  });
};

export const createAutomationJob = async (req, res) => {
  try {
    const userId = req.user._id;
    const { caption, title, body, hashtags, link, platforms } = req.body;
    let { mediaUrl } = req.body; // In case they send a URL directly instead of a file
    let cloudinaryId = null;

    if (req.file) {
      // Upload to Cloudinary using streamifier
      const uploadResult = await uploadToCloudinary(req.file.buffer);
      mediaUrl = uploadResult.secure_url;
      cloudinaryId = uploadResult.public_id;
    }

    let platformList;
    try {
      platformList = JSON.parse(platforms || "[]");
    } catch (parseError) {
      return res
        .status(400)
        .json({ error: "platforms must be a JSON array of platform ids." });
    }

    // Per-platform AI rewrites. Absent while no provider is connected, and
    // validated here so a malformed payload is rejected rather than stored.
    let platformVariants = [];
    if (req.body.platformVariants) {
      try {
        platformVariants = JSON.parse(req.body.platformVariants);
      } catch (parseError) {
        return res
          .status(400)
          .json({ error: "platformVariants must be a JSON array." });
      }
      if (!Array.isArray(platformVariants)) {
        return res
          .status(400)
          .json({ error: "platformVariants must be a JSON array." });
      }
    }

    // Same path an approved creator submission takes, so a composed post and
    // an approved one behave identically from here on.
    const result = await createAndDispatchJob({
      userId,
      content: { caption, title, body, hashtags, link },
      platforms: platformList,
      mediaUrl: mediaUrl || null,
      cloudinaryId,
      scheduledDate: req.body.scheduledDate || null,
      source: "direct",
      platformVariants,
    });

    if (!result.ok) {
      return res.status(502).json({
        error: result.error,
      });
    }

    res.status(200).json({
      message: "Post successfully scheduled in the queue",
      jobId: result.job.jobId || null,
      postId: result.job._id,
      mediaUrl,
      willPostInMinutes: Math.max(
        Math.round((result.job.scheduledDate.getTime() - Date.now()) / 60000),
        0,
      ),
    });
  } catch (error) {
    console.error("Queue Scheduling Error:", error);
    res
      .status(500)
      .json({ error: "Failed to schedule post: " + error.message });
  }
};

export const getAutomationJobs = async (req, res) => {
  try {
    const userId = req.user.id;
    const posts = await Automation.find({ userId })
      .sort({ createdAt: -1 })
      .limit(50);

    // Map database fields to the structure expected by the frontend
    const history = posts.map((post) => ({
      id: post._id,
      caption: post.title || post.body || post.caption || "New Post",
      title: post.title,
      body: post.body || post.caption,
      hashtags: post.hashtags,
      link: post.link,
      platforms: post.platforms,
      status:
        post.status === "COMPLETED"
          ? "Published"
          : post.status === "FAILED"
            ? "Failed"
            : post.status === "PARTIAL_SUCCESS"
              ? "Partial"
              : post.scheduledDate && post.scheduledDate > new Date()
                ? "Scheduled"
                : "Processing",
      scheduledFor: post.scheduledDate,
      createdAt: post.createdAt,
      thumbnail: post.mediaUrl || null,
      // Lets the history view say whether a job was composed here or
      // imported by approving a creator submission.
      source: post.source || "direct",
      creatorPostId: post.creatorPostId || null,
    }));

    res.status(200).json(history);
  } catch (error) {
    console.error("Fetch Automation History Error:", error);
    res.status(500).json({ error: "Failed to fetch automation history" });
  }
};

// POST /api/automation/enhance
// Takes universal post content and returns platform-specific variants generated by AI.
export const enhancePost = async (req, res) => {
  try {
    const { title, body, hashtags, platforms } = req.body;

    if (!platforms || platforms.length === 0) {
      return res
        .status(400)
        .json({ error: "No platforms selected for enhancement." });
    }

    const openRouterKey = process.env.OPENROUTER_API_KEY;
    const grokKey = process.env.GROK_API_KEY || process.env.XAI_API_KEY;
    const geminiKey = process.env.GEMINI_API_KEY;

    if (!openRouterKey && !grokKey && !geminiKey) {
      return res.status(500).json({
        error:
          "Please set OPENROUTER_API_KEY, GROK_API_KEY, or GEMINI_API_KEY in your backend .env file.",
      });
    }

    const systemPrompt = `You are an expert Social Media Copywriter. Take the universal social media draft and rewrite it into highly optimized, platform-specific versions for the requested platforms: ${platforms.join(", ")}.

Tone guidelines:
- youtube: Professional, structured for a video description, clear CTA.
- facebook: Conversational, relatable, appeals to millennials, friendly.
- instagram: Punchy, highly engaging, short-attention-span friendly, uses emojis.
- linkedin: Professional, insightful, business/networking oriented.

Respond ONLY with a valid JSON object where keys are the platform names (strictly lowercase matching the requested platforms) and values are the newly generated text. Include optimized hashtags at the bottom of the text for each. Do NOT wrap the response in markdown blocks like \`\`\`json.`;

    const userContent = `Universal Title: ${title || ""}\nUniversal Body: ${body || ""}\nUniversal Hashtags: ${hashtags || ""}`;

    let aiText = "";

    // 1. Try OpenRouter if configured
    if (openRouterKey) {
      const response = await axios.post(
        "https://openrouter.ai/api/v1/chat/completions",
        {
          model: "openai/gpt-4o",
          max_tokens: 1500,
          messages: [
            { role: "system", content: systemPrompt },
            { role: "user", content: userContent },
          ],
          temperature: 0.7,
        },
        {
          headers: {
            Authorization: `Bearer ${openRouterKey}`,
            "HTTP-Referer": process.env.BASE_URL || "http://localhost:5000",
            "X-Title": "APSM CrossPosting",
            "Content-Type": "application/json",
          },
        },
      );
      aiText = response.data.choices[0].message.content;
    } else if (grokKey) {
      // 2. Try Grok if configured
      const response = await axios.post(
        "https://api.x.ai/v1/chat/completions",
        {
          model: "grok-2-latest",
          messages: [
            { role: "system", content: systemPrompt },
            { role: "user", content: userContent },
          ],
          temperature: 0.7,
        },
        {
          headers: {
            Authorization: `Bearer ${grokKey}`,
            "Content-Type": "application/json",
          },
        },
      );
      aiText = response.data.choices[0].message.content;
    } else {
      // 3. Fall back to Gemini
      const response = await axios.post(
        `https://generativelanguage.googleapis.com/v1beta/models/gemini-flash-latest:generateContent?key=${geminiKey}`,
        {
          system_instruction: { parts: [{ text: systemPrompt }] },
          contents: [{ parts: [{ text: userContent }] }],
          generationConfig: { response_mime_type: "application/json" },
        },
      );
      aiText = response.data.candidates[0].content.parts[0].text;
    }

    // Safely extract and parse JSON
    const match = aiText.match(/\{[\s\S]*\}/);
    const cleanJson = match ? match[0] : aiText.trim();
    const enhancedData = JSON.parse(cleanJson);

    return res.status(200).json(enhancedData);
  } catch (error) {
    console.error(
      "Error enhancing post:",
      error.response?.data || error.message,
    );
    const errMsg = error.response?.data?.error?.message || error.message;
    return res
      .status(500)
      .json({ error: `Failed to enhance post with AI: ${errMsg}` });
  }
};
